KEY_LEN = 32

def xor_encrypt(data, key, start_offset=0):
    return bytes(b ^ key[(start_offset + i) % len(key)] for i, b in enumerate(data))

def main():
    key = os.urandom(KEY_LEN)

    # build packed encrypted data + index
    enc_data = bytearray()
    index = []

    for name, plaintext in STRINGS:
        raw = plaintext.encode('utf-8') + b'\x00'
        offset = len(enc_data)
        encrypted = xor_encrypt(raw, key, offset)
        enc_data.extend(encrypted)
        index.append((name, offset, len(raw)))

    # output C header
    out = []
    out.append("/* auto-generated by gen_obf.py -- do not edit */")
    out.append(f"#define OBF_KEY_LEN {KEY_LEN}")
    out.append(f"#define OBF_STR_COUNT {len(STRINGS)}")
    out.append("")

    # key
    key_hex = ", ".join(f"0x{b:02x}" for b in key)
    out.append(f"static const unsigned char _obf_key[OBF_KEY_LEN] = {{ {key_hex} }};")
    out.append("")

    # index
    out.append("static const struct { unsigned int off; unsigned int len; } _obf_idx[OBF_STR_COUNT] = {")
    for name, off, length in index:
        out.append(f"    /* {name} */ {{ {off}, {length} }},")
    out.append("};")
    out.append("")

    # encrypted data
    lines = []
    for i in range(0, len(enc_data), 16):
        chunk = enc_data[i:i+16]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    out.append(f"static const unsigned char _obf_data[{len(enc_data)}] = {{")
    out.extend(lines)
    out.append("};")

    print("\n".join(out))

if __name__ == "__main__":
    main()
